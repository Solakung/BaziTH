function travelLine(moves, n) {
  const good = n >= 4, bad = n <= 2;
  if (moves >= 2) return good ? 'มีแรงขยับสูง และการเปลี่ยนที่มักให้ผลดี เหมาะกับการเดินทาง ย้ายบ้าน หรือย้ายงานที่คิดไว้' : 'มีแรงให้ขยับหรือต้องย้ายแม้ไม่ได้ตั้งใจ เตรียมแผนสำรอง ตรวจเอกสารและการเดินทางให้รอบคอบ';
  if (moves === 1) return bad ? 'มีเรื่องให้ต้องเดินทางหรือเปลี่ยนแผนบ้าง เผื่อเวลาและงบไว้' : 'มีโอกาสเดินทางหรือเปลี่ยนบรรยากาศ ทริปที่วางแผนไว้มักราบรื่น';
  return good ? 'ไม่มีสัญญาณการย้ายชัด แต่การเดินทางพักผ่อนช่วยเติมพลังได้ดี' : 'ไม่มีสัญญาณการย้ายชัด ช่วงนี้เหมาะกับการปักหลักและจัดที่อยู่ให้ลงตัว';
}

function elementTip(c, topic) {
  if (!c.fav.length) return null;
  const e = c.fav[0], E = T.ELEMENT[e];
  if (topic === 'health') return `กิจกรรมที่เข้ากับธาตุที่ช่วยคุณ (${T.ELEMENT[c.fav[0]].th}${c.fav[1] != null ? `และ${T.ELEMENT[c.fav[1]].th}` : ''}): ${[...ELEMENT_LIFE[c.fav[0]].slice(0, 2), ...(c.fav[1] != null ? ELEMENT_LIFE[c.fav[1]].slice(0, 1) : [])].join(' ')}`;
  if (topic === 'travel') {
    const dirs = c.fav.slice(0, 3).filter((x) => x !== 2).map((x) => T.ELEMENT[x].direction);
    return dirs.length ? `ถ้าเลือกได้ ทิศที่ตำราโยงกับธาตุที่ช่วยคุณคือ${thList([...new Set(dirs)].map((d) => `ทิศ${d}`))}` : 'ธาตุที่ช่วยคุณคือดิน ตำราโยงกับตรงกลาง จึงเหมาะกับที่ใกล้บ้านหรือที่คุ้นเคย';
  }
  return `ใช้ธาตุ${E.th}เป็นตัวช่วยเตือนใจ เช่น สี${E.colors} หรือ${ELEMENT_LIFE[e][0]}`;
}

/**
 * อ่านดวงหนึ่งหัวข้อในหนึ่งช่วงเวลา
 * @returns โครงคำตอบ: ไพ่ (cards) ระดับ (level) หัวเรื่อง (headline) คำอ่านรายใบ (readings) สิ่งที่ทำได้ (actions) เหตุผล (why)
 */
export function readTopic(c, topic, q, intent = null) {
  // หัวข้อความรักไม่เปิดให้ผู้ที่อายุต่ำกว่า 18 ปี (บทที่ 18) ตรวจที่นี่ด้วย ไม่ใช่แค่ที่หน้าจอ
  if (topic === 'love' && c.age < 18) return { error: GUARD_TEXT.minor };
  // เจตนาจากคำถามใช้ได้เฉพาะเมื่อตรงกับหัวข้อที่อ่าน เช่น "คนใหม่" ในคำถามเรื่องหัวหน้าไม่ใช่เรื่องความรัก
  if (intent && INTENT_TOPIC[intent] !== topic) intent = null;
  const info = resolvePeriod(c, q);
  if (info.missing === 'gender') return { error: 'ต้องเลือกเพศในฟอร์มก่อน จึงจะหาวัยจร 10 ปีได้ ทิศทางของวัยจรขึ้นกับเพศและขั้วของปีเกิด' };
  if (info.missing) return { error: 'ช่วงเวลานี้อยู่นอกช่วงวัยจรที่คำนวณไว้' };
  if (info.type === 'year' && (info.Y < c.chart.baziYear || info.Y > 2100)) return { error: `ปีที่ถามต้องอยู่ระหว่าง พ.ศ. ${c.chart.baziYear + 543} (ปีเกิด) ถึง 2643` };
  const T0 = TOPIC[topic];
  const cards = [{ ...natalCard(c, topic), n: 1 }];
  let main, ctxCard = null, extra = null, weights;

  if (info.type === 'year') {
    const L = luckAt(c, info.mid);
    if (L) ctxCard = periodCard(c, topic, { idx: L.idx, type: 'decade', pre: L.pre, start: L.start, end: L.end, startAge: L.startAge, word: L.pre ? 'ช่วงก่อนวัยจรแรก' : 'วัยจร', range: L.pre ? 'ใช้เสาเดือนแทน' : `${monthYear(L.start)} – ${monthYear(L.end)}` }, 'luck', L.pre ? 'ก่อนวัยจร' : 'วัยจร 10 ปี');
    main = periodCard(c, topic, info, 'year', info.word === 'ปีนี้' || info.word === 'ปีหน้า' ? info.word : `ปี ${info.be}`);
    weights = ctxCard ? [0.7, 0.3] : [1, 0];
  } else if (info.type === 'month') {
    const yi = yearInfo(info.Y, c.nowChart.baziYear);
    ctxCard = periodCard(c, topic, yi, 'year', yi.word === 'ปีนี้' || yi.word === 'ปีหน้า' ? yi.word : `ปี ${yi.be}`);
    main = periodCard(c, topic, info, 'month', info.word);
    weights = [0.65, 0.35];
  } else if (info.type === 'day') {
    const mch = { idx: info.monthIdx, type: 'month', word: 'เดือนนี้', range: '', start: null };
    ctxCard = periodCard(c, topic, mch, 'month', 'เดือนนี้');
    main = periodCard(c, topic, info, 'day', info.word);
    weights = [0.65, 0.35];
  } else {
    main = periodCard(c, topic, info, 'luck', info.pre ? 'ก่อนวัยจร' : 'วัยจร 10 ปี');
    weights = [1, 0];
    if (!info.pre) {
      const nx = resolvePeriod(c, { type: 'decade', offset: (q.offset ?? 0) + 1 });
      if (nx.idx != null && nx.i !== info.i) extra = periodCard(c, topic, nx, 'luckNext', 'วัยจรถัดไป');
    }
  }
  if (info.type === 'year' && ctxCard && ctxCard.info.word === 'วัยจร' && Math.abs(main.ev.b - ctxCard.ev.b) === 6 && ['overall', 'health', 'career', 'travel'].includes(topic)) {
    const x = { overall: -0.2, health: -0.1 }[topic] ?? 0;
    const when = main.word === 'ปีนี้' || main.word === 'ปีหน้า' ? main.word : 'ปีนั้น';
    main.sc.notes.push(`${when}ปะทะกับวัยจรของคุณ มักมีการเปลี่ยนแปลงหลายเรื่องพร้อมกัน ควรวางแผนสำรองไว้`);
    main.sc.why.push(`กิ่งปี ${B.BRANCHES[main.ev.b]} ปะทะกิ่งวัยจร ${B.BRANCHES[ctxCard.ev.b]} (岁运相冲)${x ? ` (${x.toFixed(2).replace('-', '−')})` : ''}`);
    main.sc.score = +Math.max(-1.2, main.sc.score + x).toFixed(2);
    if (topic === 'travel') { main.sc.moves += 1; main.sc.active = true; }
  }
  if (ctxCard) cards.push({ ...ctxCard, n: 2 });
  cards.push({ ...main, n: cards.length + 1 });
  if (extra) cards.push({ ...extra, n: cards.length + 1 });

  const tilt = natalTilt(c, topic);
  const score = +Math.max(-1.2, Math.min(1.2, weights[0] * main.sc.score + (ctxCard ? weights[1] * ctxCard.sc.score : 0) + tilt)).toFixed(2);
  const level = levelOf(score);
  const LV = topic === 'health' ? HEALTH_LEVELS : topic === 'money' ? MONEY_LEVELS : LEVELS;
  const tone = toneOf(level);
  const groups = main.ev.parts.map((p) => p.group);
  const r = { level, active: main.sc.active, moves: main.sc.moves, flags: main.sc.flags, groups };

  // หัวเรื่อง
  const subject = `${T0.th}${main.word === 'ปีนี้' || main.word === 'ปีหน้า' ? main.word : `ช่วง${main.label}`}`;
  let headline = intentLine(intent, r);
  const travelFirst = topic === 'travel' && !!headline;
  if (!headline) {
    if (topic === 'travel') headline = travelLine(r.moves, level);
    else if (!r.active && level !== 3 && topic === 'health') headline = `${T0.th}ไม่ใช่ธีมหลักของช่วงนี้ ${LV[level].desc}`;
    else if (!r.active && level !== 3 && topic !== 'overall') headline = `${T0.th}ไม่ใช่ธีมหลักของช่วงนี้ แต่บรรยากาศโดยรวม${level >= 4 ? 'หนุนอยู่ ค่อย ๆ เดินหน้าได้' : 'มีแรงต้าน ต้องวางแผนและออกแรงมากกว่าปกติ'}`;
    else if (!r.active && topic !== 'overall') headline = `${T0.th}ไม่ใช่ธีมหลักของช่วงนี้ จึงมักทรงตัวตามที่คุณดูแล`;
    else headline = LV[level].desc;
  }

  // คำอ่านรายใบ
  const readings = [{ n: 1, label: 'พื้นดวง', text: cards[0].line }];
  if (ctxCard) readings.push({ n: 2, label: ctxCard.label, text: contextLine(ctxCard) });
  const mn = ctxCard ? 3 : 2;
  const lines = mainLines(c, topic, main);
  if (travelFirst) lines.unshift({ when: null, text: travelLine(r.moves, level) });
  readings.push({ n: mn, label: main.label, lines, notes: main.sc.notes });
  if (extra) {
    const echo = extra.ev.echo.map((e) => `${e.type === '伏吟' ? 'ซ้ำรอย' : 'ย้อนรอย'}เสา${PALACE_TH[e.k]}ในผัง`);
    readings.push({ n: mn + 1, label: 'วัยจรถัดไป', text: `${extra.ev.name} เริ่ม ${monthYear(extra.info.start)} เด่นเรื่อง${extra.title} เรื่องนี้อยู่ในระดับ "${LV[levelOf(extra.sc.score)].label}"${echo.length ? ` และ${echo.join(' ')} ตำราถือเป็นช่วงที่ควรใส่ใจ` : ''}` });
  }

  // ปีชง
  let taisui = null;
  if (info.type === 'year' && ['overall', 'health', 'travel', 'people'].includes(topic)) {
    const list = B.taiSuiRelations(c.P.year % 12, info.Y);
    const top = TAISUI_ORDER.find((x) => list.includes(x));
    if (top) taisui = { text: TAISUI_PLAIN[top](info.word === 'ปีนี้' ? 'ปีนี้' : info.word === 'ปีหน้า' ? 'ปีหน้า' : `ปี ${info.be} `), list };
  }

  // สิ่งที่ทำได้
  const actions = [...ACTIONS[topic][tone], elementTip(c, topic)].filter(Boolean);

  // เหตุผล (ศัพท์จริง) ตามหลักความโปร่งใสในบทที่ 18
  const st = c.A.favorable.strength;
  const thEls = (a) => (a.length ? a.map((e) => T.ELEMENT[e].th).join(' ') : 'ไม่มี');
  const favWhy = c.schools
    ? `ธาตุที่ทุกแนวเห็นตรงกัน: ${thEls(c.schools.both)} · ${c.schools.follow.name}: ${thEls(c.schools.follow.fav)} · ${c.schools.normal.name}: ${thEls(c.schools.normal.fav)} · ธาตุที่สองแนวเห็นต่างนับเป็นกลาง`
    : `ธาตุให้คุณ: ${thEls(c.fav)}`;
  const favWord = (f) => (f > 0 ? 'ให้คุณ' : f < 0 ? 'ให้โทษ' : 'ขึ้นกับสำนัก');
  const partWhy = (card) => card.ev.parts.map((p) => `${p.part === 'stem' ? 'ก้าน' : 'กิ่ง'} ${p.char}${p.part === 'branch' ? ` (ก้านหลัก ${B.STEMS[B.HIDDEN_STEMS[card.ev.b][0]]})` : ''} เป็น ${B.TEN_GODS[p.god]} ${T.GOD[B.TEN_GODS[p.god]].th} ธาตุ${T.ELEMENT[p.el].th} ${favWord(p.fav)}`).join(' · ');
  const why = [
    `เจ้าวัน ${B.STEMS[c.dm]} ${T.STEM[c.dm].kind} กำลัง${({ veryStrong: 'แข็งมาก', strong: 'แข็ง', balanced: 'ค่อนข้างสมดุล', weak: 'อ่อน', veryWeak: 'อ่อนมาก' })[c.level]} (${(st.ratio * 100).toFixed(1)}%) ${favWhy}`,
    `${main.label} ${main.ev.name}: ${partWhy(main)} แรงหนุนรวม ${main.ev.base >= 0 ? '+' : '−'}${Math.abs(main.ev.base).toFixed(1)} (ก้าน 0.4 กิ่ง 0.6)`,
    ...main.sc.why,
  ];
  if (ctxCard) why.push(`${ctxCard.label} ${ctxCard.ev.name}: ${partWhy(ctxCard)}`);
  if (taisui) why.push(`ปีชง: ${taisui.list.map((x) => `${T.TAISUI[x]} ${x}`).join(' · ')}`);
  if (tilt) why.push(`พื้นดวง: ธาตุหลักของหัวข้อนี้${tilt > 0 ? 'เป็นธาตุให้คุณ (+0.08)' : 'เป็นธาตุให้โทษ (−0.08)'}`);
  why.push(`คะแนนรวม ${score >= 0 ? '+' : '−'}${Math.abs(score).toFixed(2)} = ${main.label} × ${weights[0]}${ctxCard ? ` + ${ctxCard.label} × ${weights[1]}` : ''}${tilt ? ' + พื้นดวง' : ''} · ช่วงคะแนน −1.2 ถึง +1.2 · เกณฑ์เป็นกฎตั้งต้นรุ่นแรกตามบทที่ 15.2 ของตำรา ควรให้ผู้รู้ปรับ`);

  const notes = [];
  if (TOPIC_NOTE[topic]) notes.push(TOPIC_NOTE[topic]);
  if (c.schools) notes.push('ผังของคุณเป็นแบบสุดขั้ว ซึ่งตำราแต่ละสำนักอ่านต่างกัน คำอ่านนี้นับเฉพาะธาตุที่ทุกแนวเห็นตรงกัน ธาตุอื่นนับเป็นกลาง');

  return {
    topic, topicTh: T0.th, period: info, subject, cards, score, level, levelInfo: LV[level], active: r.active,
    headline, readings, taisui, actions, why, notes,
  };
}

