const HALVES = { year: { stem: 'ช่วงต้นปี', branch: 'ช่วงปลายปี' }, decade: { stem: '5 ปีแรก', branch: '5 ปีหลัง' } };

function mainLines(c, topic, card) {
  const halves = card.info.pre ? null : HALVES[card.info.type];
  const lines = [];
  const [ps, pb] = card.ev.parts;
  let parts = !halves && ps.group === pb.group && ps.fav === pb.fav ? [pb] : card.ev.parts;
  // ดาวคู่ครองทั้งก้านและกิ่ง: ใช้บรรทัดเดียว เลือกดาวคู่ครองตัวตรง (正) ก่อน ไม่ให้ "จริงจัง" กับ "สบาย ๆ" ขึ้นคู่กัน
  if (topic === 'love' && ps.group === pb.group && ps.group === spouseGroup(c) && ps.fav === pb.fav) {
    parts = [card.ev.parts.find((p) => p.god === 5 || p.god === 7) ?? pb];
  }
  for (const p of parts) {
    const text = topicText(c, topic, p);
    if (lines.some((l) => l.text === text)) continue;
    lines.push({ when: halves?.[p.part] ?? null, text });
  }
  if (lines.length === 1) lines[0].when = null;
  return lines;
}

