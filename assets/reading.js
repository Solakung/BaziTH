/**
 * รวมข้อมูลที่ตัวตีความต้องใช้ · now คือเวลานาฬิกาไทย { y, m, d, h, mi }
 */
export function makeContext({ chart, A, now }) {
  const P = chart.pillars, dm = P.day % 10;
  const nowChart = B.computeChart({ year: now.y, month: now.m, day: now.d, hour: now.h, minute: now.mi, timeZone: TZ });
  const luck = chart.gender ? B.luckPillars(chart, 10) : null;
  const birth = { y: chart.input.year, m: chart.input.month, d: chart.input.day };
  let age = now.y - birth.y;
  if (now.m < birth.m || (now.m === birth.m && now.d < birth.d)) age -= 1;
  const natalParts = [];
  for (const k of ['year', 'month', 'day', 'hour']) {
    if (P[k] == null) continue;
    if (k !== 'day') natalParts.push({ k, part: 'stem', god: B.tenGod(dm, P[k] % 10) });
    natalParts.push({ k, part: 'branch', god: B.tenGod(dm, B.HIDDEN_STEMS[P[k] % 12][0]) });
  }
  const level = A.favorable.strength.level, E = dm >> 1;
  const schools = schoolsOf(A.favorable, E, level);
  // ผังสุดขั้ว: นับเฉพาะธาตุที่ทุกแนวเห็นตรงกัน ธาตุที่สองแนวเห็นต่างนับเป็นกลาง (บทที่ 12 และ 16 ข้อ 4)
  const fav = schools ? schools.both : A.favorable.favorable;
  const unfav = schools ? schools.neither : A.favorable.unfavorable;
  return {
    chart, A, P, dm, E, now, nowChart, luck, age, level, schools, fav, unfav,
    favScore: (e) => (fav.includes(e) ? 1 : unfav.includes(e) ? -1 : 0),
    gender: chart.gender, weights: A.favorable.strength.weights, natalParts,
    natalStars: new Set(A.stars.map((s) => s.name)),
  };
}

/**
 * ผังที่แข็งมากหรืออ่อนมาก ตำรามีสองแนวที่ให้ธาตุให้คุณต่างกัน (บทที่ 12)
 * bazi-core คืนแนว "ตาม" ส่วนแนวปกติคิดซ้ำที่นี่ด้วยตารางตัดสินใจเดียวกัน แล้วหาจุดที่ตรงกัน
 */
export function schoolsOf(F, E, level) {
  if (!F.special) return null;
  const w = F.strength.weights, rel = (k) => B.mod(E + k, 5);
  let normal;
  if (level === 'veryStrong') {
    normal = w[rel(4)] > w[rel(0)] ? [rel(2), rel(1), rel(3)] : w[rel(3)] >= 1 ? [rel(3), rel(1), rel(2)] : [rel(1), rel(2), rel(3)];
  } else {
    normal = [rel(4), rel(0)];
  }
  if (F.climate != null && !normal.includes(F.climate)) normal = [...normal, F.climate];
  const follow = F.favorable;
  const strong = level === 'veryStrong';
  return {
    follow: { name: strong ? 'แนวตามแข็ง' : 'แนวตามอ่อน', fav: follow },
    normal: { name: strong ? 'แนวแข็งปกติ' : 'แนวอ่อนปกติ', fav: normal },
    both: normal.filter((e) => follow.includes(e)),
    neither: [0, 1, 2, 3, 4].filter((e) => !follow.includes(e) && !normal.includes(e)),
  };
}

