/** ประเมินเสาของช่วงเวลาหนึ่งเทียบกับผังเกิด */
export function evalPillar(c, idx) {
  const s = idx % 10, b = idx % 12;
  const parts = [
    { part: 'stem', char: B.STEMS[s], god: B.tenGod(c.dm, s), el: s >> 1, w: 0.4 },
    { part: 'branch', char: B.BRANCHES[b], god: B.tenGod(c.dm, B.HIDDEN_STEMS[b][0]), el: B.BRANCH_ELEMENT[b], w: 0.6 },
  ];
  for (const p of parts) { p.group = p.god >> 1; p.fav = c.favScore(p.el); }
  const base = parts.reduce((a, p) => a + p.w * p.fav, 0);
  const rel = {};
  for (const k of ['year', 'month', 'day', 'hour']) {
    if (c.P[k] != null) rel[k] = B.branchRelations(b, c.P[k] % 12).map((r) => r.type);
  }
  const dmCombine = B.stemRelations(s, c.dm).some((r) => r.type === '合');
  const stars = [...new Set(B.symbolicStars({ ...c.P, flow: idx }).filter((f) => f.at.includes('flow') && f.name !== '空亡').map((f) => f.name))];
  // ซ้ำรอย 伏吟 = ตรงกับเสาในผังทุกตัวอักษร · ย้อนรอย 反吟 = ก้านปะทะและกิ่งปะทะเสาในผังพร้อมกัน (บทที่ 15.1)
  const echo = [];
  for (const k of ['year', 'month', 'day', 'hour']) {
    const n = c.P[k];
    if (n == null) continue;
    if (n === idx) echo.push({ k, type: '伏吟' });
    else if (Math.abs((n % 10) - s) === 6 && Math.abs((n % 12) - b) === 6) echo.push({ k, type: '反吟' });
  }
  return { idx, s, b, name: B.gzName(idx), parts, base: +base.toFixed(2), rel, dmCombine, stars, echo };
}

