const dict = (rows, mapper) => rows.flatMap((row) => row[row.length - 1].split(' ').map((w) => mapper(w, row))).sort((a, b) => b.w.length - a.w.length);
const TOPIC_DICT = dict(TOPIC_WORDS, (w, [topic, weight]) => ({ w, v: topic, weight }));
const INTENT_DICT = dict(INTENT_WORDS, (w, [v]) => ({ w, v, weight: 1 }));
const GUARD_DICT = dict(GUARD_WORDS, (w, [v]) => ({ w, v, weight: 1 }));

/** หาคำในข้อความแบบคำยาวก่อน ไม่ให้ "งาน" ใน "แต่งงาน" ถูกนับซ้ำ */
function scan(text, entries) {
  const claimed = new Uint8Array(text.length);
  const hits = [];
  for (const e of entries) {
    let i = text.indexOf(e.w);
    while (i >= 0) {
      let free = true;
      for (let j = i; j < i + e.w.length; j++) if (claimed[j]) { free = false; break; }
      if (free) { claimed.fill(1, i, i + e.w.length); hits.push({ ...e, i }); }
      i = text.indexOf(e.w, i + 1);
    }
  }
  return hits;
}
const pickBest = (hits) => {
  hits = hits.filter((h) => h.v !== '_');
  if (!hits.length) return null;
  const sum = new Map();
  for (const h of hits) { const s = sum.get(h.v) ?? { v: h.v, total: 0, first: h.i }; s.total += h.weight; s.first = Math.min(s.first, h.i); sum.set(h.v, s); }
  return [...sum.values()].sort((a, b) => b.total - a.total || a.first - b.first)[0].v;
};

// ไม่ใช้ lookbehind เพราะ Safari ก่อน 16.4 แปลไม่ได้ ใช้ (?:^|\D) แทน
const MONTH_RE = [/มกรา|ม\.ค\./, /กุมภา|ก\.พ\./, /มีนา(?!ย)|มี\.ค\./, /เมษา|เม\.ย\./, /พฤษภา|พ\.ค\./, /มิถุนา|มิ\.ย\./,
  /กรกฎา|ก\.ค\./, /สิงหา|ส\.ค\./, /กันยา|ก\.ย\./, /ตุลา(?!การ)|ต\.ค\./, /พฤศจิกา|พ\.ย\./, /ธันวา|ธ\.ค\./];
const TH_NUM = { หนึ่ง: 1, สอง: 2, สาม: 3, สี่: 4, ห้า: 5, หก: 6, เจ็ด: 7, แปด: 8, เก้า: 9 };

/**
 * แยกคำถามเป็นหัวข้อ ช่วงเวลา เจตนา และเรื่องที่ไม่ทำนาย
 * now คือเวลานาฬิกาไทย · nowBaziYear คือปีปาจื้อปัจจุบัน (ค.ศ.)
 */
export function parseQuestion(raw, now, nowBaziYear) {
  const text = String(raw || '').replace(/[๐-๙]/g, (d) => String('๐๑๒๓๔๕๖๗๘๙'.indexOf(d))).replace(/\s+/g, '').toLowerCase();
  if (!text) return { empty: true, topic: null, period: null, intent: null, guard: null, soft: [] };
  const topic = pickBest(scan(text, TOPIC_DICT));
  const intent = pickBest(scan(text, INTENT_DICT));
  const guards = [...new Set(scan(text, GUARD_DICT).map((h) => h.v).filter((v) => v !== '_'))];

  // ตัดตัวเลขที่ไม่ใช่ช่วงเวลาที่ถามออกก่อน: ปีเกิด อายุ และการสอบ ก.พ. (สำนักงานข้าราชการพลเรือน ไม่ใช่เดือน)
  const t = text
    .replace(/(?:ปี)?เกิด(?:ปี)?(?:พ\.?ศ\.?|ค\.?ศ\.?)?\d{2,4}/g, '')
    .replace(/อายุ\d{1,3}/g, '')
    .replace(/สอบก\.?พ\.?/g, 'สอบราชการ')
    .replace(/(อีก|^|\D)(หนึ่ง|สอง|สาม|สี่|ห้า|หก|เจ็ด|แปด|เก้า)ปี/g, (m, a, w) => `${a}${TH_NUM[w]}ปี`);

  let yearNum = null;
  const be = t.match(/(?:^|\D)(2[45]\d\d|26\d\d)(?!\d)/), ce = t.match(/(?:^|\D)(19\d\d|20\d\d)(?!\d)/), shortBe = t.match(/ปี(?:พ\.?ศ\.?)?(\d{2})(?!\d)/);
  if (be) yearNum = +be[1] - 543;
  else if (ce) yearNum = +ce[1];
  else if (shortBe && !/^(\d{2})ปี/.test(t.slice(shortBe.index + shortBe[0].length - 2))) yearNum = 2500 + +shortBe[1] - 543;
  if (yearNum != null && (yearNum < 1900 || yearNum > 2100)) yearNum = null;

  const mi = MONTH_RE.findIndex((re) => re.test(t));
  const ahead = t.match(/อีก(\d{1,2})ปี/);
  const span = t.match(/(\d{1,2})ปี(ข้างหน้า|ต่อจากนี้|นี้)/);
  let period = null;
  if (/มะรืน/.test(t)) period = { type: 'day', offset: 2 };
  else if (/พรุ่งนี้/.test(t)) period = { type: 'day', offset: 1 };
  else if (/วันนี้/.test(t)) period = { type: 'day', offset: 0 };
  else if (mi >= 0) {
    const m = mi + 1;
    const Y = yearNum ?? (/ปีหน้า|ปีถัดไป/.test(t) ? now.y + 1 : /ปีนี้/.test(t) ? now.y : m >= now.m ? now.y : now.y + 1);
    period = { type: 'month', Y, m };
  } else if (/เดือนหน้า|เดือนถัดไป/.test(t)) period = { type: 'month', offset: 1 };
  else if (/เดือนนี้|ช่วงนี้|ตอนนี้|ระยะนี้|สัปดาห์นี้|อาทิตย์นี้/.test(t)) period = { type: 'month', offset: 0 };
  else if (yearNum != null) period = { type: 'year', Y: yearNum };
  else if (/ปีหน้า|ปีถัดไป/.test(t)) period = { type: 'year', offset: 1 };
  else if (ahead) period = { type: 'year', Y: nowBaziYear + Math.min(+ahead[1], 60) };
  else if (/10ปี|สิบปี/.test(t) || (span && +span[1] >= 5)) period = { type: 'decade', offset: 0 };
  else if (span) period = span[2] === 'นี้' ? { type: 'year', offset: 0 } : { type: 'year', Y: nowBaziYear + +span[1] };
  else if (/ปีนี้/.test(t)) period = { type: 'year', offset: 0 };
  else if (/วัยจร|ระยะยาว|อนาคต|ช่วงชีวิต/.test(t)) period = { type: 'decade', offset: 0 };

  const hard = HARD_GUARDS.find((g) => guards.includes(g)) ?? null;
  return { empty: false, topic: topic ?? INTENT_TOPIC[intent] ?? null, period, intent, guard: hard, soft: guards.filter((g) => !HARD_GUARDS.includes(g)) };
}

