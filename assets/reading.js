/** เหตุผลที่ธาตุ x เป็นธาตุให้คุณ (บทที่ 12) */
export function whyFavorable(c, x) {
  const F = c.A.favorable, k = B.mod(x - c.E, 5);
  if (F.climate === x) {
    const cold = [11, 0, 1].includes(c.P.month % 12);
    return cold ? 'คุณเกิดหน้าหนาวและผังมีไฟน้อย ตำราให้เติมไฟเพื่อความอบอุ่น เรียกว่าการปรับอากาศ' : 'คุณเกิดหน้าร้อนและผังมีน้ำน้อย ตำราให้เติมน้ำเพื่อความชุ่มชื้น เรียกว่าการปรับอากาศ';
  }
  if (c.level === 'veryStrong') return 'พลังที่ล้นต้องมีทางออก ธาตุนี้ช่วยระบายพลังออกมาเป็นผลงาน และเป็นธาตุที่ทุกแนวเห็นตรงกัน';
  if (c.level === 'veryWeak') return 'เป็นธาตุที่ทุกแนวเห็นตรงกัน';
  if (k === 0 || k === 4) return 'คุณต้องการแรงหนุน ธาตุนี้จึงช่วยเติมพลังให้';
  return 'คุณมีพลังเหลือ ธาตุนี้ช่วยใช้พลังนั้นให้เกิดประโยชน์';
}

export function easySummary(c) {
  const st = c.A.favorable.strength;
  const S = STRENGTH_PLAIN[c.level];
  const lean = c.level === 'balanced' ? (st.ratio < B.BALANCE_PIVOT ? ' ค่อนไปทางน้อย' : ' ค่อนไปทางมาก') : '';
  const fav = c.fav.map((e) => ({ e, role: roleOf(c.E, e), why: whyFavorable(c, e), life: ELEMENT_LIFE[e] }));
  let decade = null;
  if (c.luck) {
    const q = { type: 'decade', offset: 0 };
    const info = resolvePeriod(c, q);
    const ev = evalPillar(c, info.idx);
    const lines = ev.parts.map((p) => ({ when: info.pre ? null : HALVES.decade[p.part], theme: GOD_PLAIN[p.god].theme, text: p.fav === 0 ? `ผลดีหรือหนักของธาตุ${T.ELEMENT[p.el].th}ในผังแบบคุณ ตำราแต่ละสำนักอ่านต่างกัน` : GOD_PLAIN[p.god][p.fav > 0 ? 'good' : 'bad'] }));
    const echo = ev.echo.map((e) => (e.type === '伏吟'
      ? `วัยจรนี้ตรงกับเสา${PALACE_TH[e.k]}ในผังทุกตัวอักษร (${PALACE_DOMAIN[e.k]}) ตำราเรียกว่าซ้ำรอย และถือเป็นช่วงที่ควรใส่ใจ`
      : `วัยจรนี้ปะทะเสา${PALACE_TH[e.k]}ในผังทั้งตัวบนและตัวล่าง (${PALACE_DOMAIN[e.k]}) ตำราเรียกว่าย้อนรอย และถือเป็นช่วงที่ควรใส่ใจ`));
    decade = { info, ev, echo, tone: supportPlain(ev.base), lines: lines[0].text === lines[1].text ? [{ ...lines[0], when: null }] : lines };
  }
  const years = [0, 1].map((offset) => readTopic(c, 'overall', { type: 'year', offset }));
  return {
    persona: { stem: c.dm, title: T.STEM[c.dm].image, text: personaText(c.dm, c.level) },
    strength: { ...S, label: S.label + lean, ratio: st.ratio },
    fav, unfav: c.unfav, schools: c.schools, decade, years,
  };
}

