      if (ev.dmCombine) add(0.2, 'ก้านของช่วงนี้รวมกับตัวคุณ ตำรามองว่าเป็นแรงดึงดูดระหว่างคุณกับคนอื่น', `ก้าน ${ev.parts[0].char} รวมกับเจ้าวัน ${B.STEMS[c.dm]} (合)`);
      if (star('桃花')) add(0.1, 'ดาวดอกท้อมาเยือน เสน่ห์แรงขึ้น คนเข้าหาง่ายขึ้น', `${fb} เป็นดาว 桃花`);
