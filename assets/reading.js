export const wallOfMs = (ms) => {
  const t = new Date(ms + H7);
  return { y: t.getUTCFullYear(), m: t.getUTCMonth() + 1, d: t.getUTCDate(), h: t.getUTCHours(), mi: t.getUTCMinutes() };
};
const wallOfJD = (jd) => wallOfMs(B.jdToMs(jd));
const msOf = (t) => Date.UTC(t.y, t.m - 1, t.d, t.h ?? 0, t.mi ?? 0) - H7;
const addDays = (t, n) => wallOfMs(msOf(t) + n * 864e5);
const beYear = (y, m) => (y < 1941 && m <= 3 ? y + 542 : y + 543);
const dShort = (t) => `${t.d} ${T.MONTHS_SHORT[t.m - 1]} ${beYear(t.y, t.m)}`;
const dNoYear = (t) => `${t.d} ${T.MONTHS_SHORT[t.m - 1]}`;
const monthYear = (t) => `${T.MONTHS_SHORT[t.m - 1]} ${beYear(t.y, t.m)}`;
const range = (a, z) => (a.y === z.y ? `${dNoYear(a)} – ${dShort(z)}` : `${dShort(a)} – ${dShort(z)}`);
const chartAt = (t) => B.computeChart({ year: t.y, month: t.m, day: t.d, hour: t.h ?? 12, minute: t.mi ?? 0, timeZone: TZ });

