/** หาวัยจรที่ครอบเวลา t (วันที่นาฬิกาไทย) */
export function luckAt(c, t) {
  if (!c.luck) return null;
  const at = msOf(t);
  let i = -1;
  c.luck.pillars.forEach((p, k) => { if (msOf(p.startDate) <= at) i = k; });
  if (i < 0) return { pre: true, i: -1, idx: c.P.month, end: c.luck.pillars[0].startDate };
  const p = c.luck.pillars[i];
  const end = i + 1 < c.luck.pillars.length ? c.luck.pillars[i + 1].startDate : { ...p.startDate, y: p.startDate.y + 10 };
  return { pre: false, i, idx: p.index, start: p.startDate, end, startAge: Math.floor(p.startAge) };
}

